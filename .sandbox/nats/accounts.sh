#!/usr/bin/env bash
# Regenerates accounts.conf from accounts.d/: one file per account, named
# after it, holding that account's password. Run on the host by sandbox.just;
# the server picks up changes on SIGHUP.
set -euo pipefail
dir="$(cd "$(dirname "$0")" && pwd)"
mkdir -p "$dir/accounts.d"
[ -f "$dir/accounts.d/shared" ] || od -An -N16 -tx1 /dev/urandom | tr -d ' \n' > "$dir/accounts.d/shared"

{
    echo "# Generated by accounts.sh from accounts.d/. Do not edit."
    echo "accounts {"
    for f in "$dir"/accounts.d/*; do
        a="$(basename "$f")"
        echo "  $a: { jetstream: enabled, users: [{ user: $a, password: \"$(cat "$f")\" }] }"
    done
    echo "}"
} > "$dir/accounts.conf.tmp"
# Replace rather than rewrite, so the server never reads a half-written file.
mv "$dir/accounts.conf.tmp" "$dir/accounts.conf"
